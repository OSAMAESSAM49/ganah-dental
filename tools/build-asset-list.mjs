#!/usr/bin/env node
/**
 * Regenerates asset-list.js: every file the app needs offline + a content hash as VERSION.
 * Usage:  node tools/build-asset-list.mjs          (write)
 *         node tools/build-asset-list.mjs --check  (exit 1 if out of date — use before committing)
 * Plain Node, no dependencies.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const INCLUDE_DIRS = ['css', 'js', 'vendor', 'assets'];
const INCLUDE_FILES = ['index.html', 'manifest.webmanifest'];
const SKIP = [/\.DS_Store$/, /\.map$/, /(^|\/)LICENSE/i, /\.md$/, /OFL\.txt$/];

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = [
  ...INCLUDE_FILES.map((f) => join(ROOT, f)),
  ...INCLUDE_DIRS.filter((d) => existsSync(join(ROOT, d))).flatMap((d) => walk(join(ROOT, d))),
]
  .map((f) => relative(ROOT, f).split(sep).join('/'))
  .filter((f) => !SKIP.some((re) => re.test(f)))
  .sort();

const hash = createHash('sha256');
for (const f of files) { hash.update(f); hash.update(readFileSync(join(ROOT, f))); }
hash.update(readFileSync(join(ROOT, 'sw.js')));
const version = hash.digest('hex').slice(0, 12);

const out = `/* Generated by tools/build-asset-list.mjs — do not edit by hand. */
self.ASSET_VERSION = '${version}';
self.ASSETS = ${JSON.stringify(['./', ...files.map((f) => './' + f)], null, 2)};
`;

const target = join(ROOT, 'asset-list.js');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== out) { console.error('asset-list.js is out of date. Run: node tools/build-asset-list.mjs'); process.exit(1); }
  console.log(`asset-list.js is up to date (${files.length} files, version ${version}).`);
} else {
  writeFileSync(target, out);
  console.log(`asset-list.js written: ${files.length} files, version ${version}.`);
}
